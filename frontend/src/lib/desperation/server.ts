/**
 * Import/refresh a week's schedule from ESPN. Upserts nd_weeks + nd_games.
 * If ESPN moved a game to a different week (Rule 8), picks on it are deleted.
 */
export async function syncScheduleWeek(admin: Admin, seasonYear: number, week: number) {
  const board = await fetchEspnWeek(seasonYear, week)
  const mapped = (board.events ?? [])
    .map((e) => mapEspnEvent(e, seasonYear, week))
    .filter((g): g is NonNullable<typeof g> => g !== null)

  if (mapped.length === 0) return { games: 0, movedGames: 0 }

  const kickoffs = mapped.map((g) => g.kickoff_at)
  const lockAt = computeWeekLockAt(kickoffs)
  const first = kickoffs.reduce((a, b) => (a < b ? a : b))
  const last = kickoffs.reduce((a, b) => (a > b ? a : b))

  const { error: weekErr } = await admin.from('nd_weeks').upsert(
    {
      season_year: seasonYear,
      week_number: week,
      lock_at: lockAt.toISOString(),
      first_kickoff_at: first,
      last_kickoff_at: last,
    },
    { onConflict: 'season_year,week_number' }
  )
  if (weekErr) throw new Error(`nd_weeks upsert: ${weekErr.message}`)

  // Detect games that moved weeks so their picks can be cleared (Rule 8)
  const { data: existing } = await admin
    .from('nd_games')
    .select('id, espn_game_id, week_number')
    .eq('season_year', seasonYear)
    .in('espn_game_id', mapped.map((g) => g.espn_game_id))
  const moved = (existing ?? []).filter((e) => e.week_number !== week)

  const now = new Date().toISOString()
  const { error: gamesErr } = await admin.from('nd_games').upsert(
    mapped.map((g) => ({ ...g, last_synced_at: now })),
    { onConflict: 'season_year,espn_game_id' }
  )
  if (gamesErr) throw new Error(`nd_games upsert: ${gamesErr.message}`)

  if (moved.length > 0) {
    await admin.from('nd_picks').delete().in('game_id', moved.map((m) => m.id))
  }

  await refreshWeekStatus(admin, seasonYear, week)
  return { games: mapped.length, movedGames: moved.length }
}

/**
 * Refresh live scores for a week from ESPN, then recompute scores + week status.
 * Throttled: returns { synced: false } if the week was synced within the last 20s.
 */
export async function syncScoresWeek(admin: Admin, seasonYear: number, week: number, opts: { force?: boolean } = {}) {
  const games = await getWeekGames(admin, seasonYear, week)
  if (games.length === 0) return { synced: false, reason: 'no games' as const }

  const newest = Math.max(...games.map((g) => (g.last_synced_at ? new Date(g.last_synced_at).getTime() : 0)))
  if (!opts.force && Date.now() - newest < SYNC_THROTTLE_MS) {
    return { synced: false, reason: 'throttled' as const }
  }

  const board = await fetchEspnWeek(seasonYear, week)
  const now = new Date().toISOString()
  const byEspn = new Map(games.map((g) => [g.espn_game_id, g]))

  const updates = (board.events ?? [])
    .map((e) => mapEspnEvent(e, seasonYear, week))
    .filter((g): g is NonNullable<typeof g> => g !== null && byEspn.has(g.espn_game_id))

  await Promise.all(
    updates.map((g) =>
      admin
        .from('nd_games')
        .update({
          home_score: g.home_score,
          away_score: g.away_score,
          status: g.status,
          period: g.period,
          clock: g.clock,
          winner: g.winner,
          qualifies: g.qualifies,
          kickoff_at: g.kickoff_at, // flexed/postponed times
          last_synced_at: now,
          // Line drifts all week; refresh it, but don't wipe a known line if ESPN omits odds
          ...(g.odds_details !== null
            ? { spread: g.spread, over_under: g.over_under, odds_details: g.odds_details, odds_provider: g.odds_provider }
            : {}),
        })
        .eq('season_year', seasonYear)
        .eq('espn_game_id', g.espn_game_id)
    )
  )

  await recomputeWeekScores(admin, seasonYear, week)
  await refreshWeekStatus(admin, seasonYear, week)
  return { synced: true, reason: 'ok' as const, updated: updates.length }
}

/** True if a page load should trigger a score refresh before rendering. */
export function shouldLazySync(games: NdGame[], now: Date = new Date()): boolean {
  if (games.length === 0) return false
  const active = games.some(
    (g) => g.status === 'in_progress' || (g.status === 'scheduled' && new Date(g.kickoff_at) <= now)
  )
  if (!active) return false
  const newest = Math.max(...games.map((g) => (g.last_synced_at ? new Date(g.last_synced_at).getTime() : 0)))
  return now.getTime() - newest > LAZY_SYNC_STALE_MS
}

async function refreshWeekStatus(admin: Admin, seasonYear: number, week: number) {
  const games = await getWeekGames(admin, seasonYear, week)
  const { data: w } = await admin
    .from('nd_weeks')
    .select('lock_at, status')
    .eq('season_year', seasonYear)
    .eq('week_number', week)
    .single()
  if (!w || games.length === 0) return

  const now = new Date()
  let status: NdWeek['status']
  const allTerminal = games.every(isTerminal)
  if (allTerminal) status = 'final'
  else if (games.some((g) => g.status === 'in_progress' || (g.status === 'final'))) status = 'in_progress'
  else if (now >= new Date(w.lock_at)) status = 'locked'
  else if (games.some((g) => new Date(g.kickoff_at) <= now)) status = 'in_progress'
  else status = 'open'

  const patch: Tables['nd_weeks']['Update'] = { status }
  if (status === 'final' && w.status !== 'final') patch.finalized_at = now.toISOString()
  await admin.from('nd_weeks').update(patch).eq('season_year', seasonYear).eq('week_number', week)
}

