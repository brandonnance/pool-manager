export interface JoinState {
  open: boolean
  reason: JoinClosedReason | null
  /** Week a joiner would start competing in; null when unknown or the season is over */
  joinWeek: number | null
  weeks: NdWeek[]
}

/** Can someone holding the pool's public link create their own entry right now? */
export async function getJoinState(admin: Admin, ndPool: NdPoolRow, poolStatus: string, now: Date = new Date()): Promise<JoinState> {
  const weeks = await getWeeks(admin, ndPool.season_year)
  const joinWeek = joinWeekFor(weeks, now)
  const closed = (reason: JoinClosedReason): JoinState => ({ open: false, reason, joinWeek, weeks })
  if (poolStatus !== 'open') return closed('pool_closed')
  if (!ndPool.self_join_enabled) return closed('self_join_off')
  if (weeks.length === 0) return closed('no_schedule')
  if (joinWeek === null) return closed('season_over')
  if (joinWeek > 1 && !ndPool.allow_midseason_join) return closed('midseason_closed')
  return { open: true, reason: null, joinWeek, weeks }
}

