type Admin = SupabaseClient<Database>
type Tables = Database['public']['Tables']
export type NdEntryRow = Tables['nd_entries']['Row']
export type NdPoolRow = Tables['nd_pools']['Row']

/** Hex token generated by the DB default: encode(gen_random_bytes(24),'hex') */
const TOKEN_RE = /^[a-f0-9]{48}$/

/** Don't hit ESPN more often than this for the same week. */
const SYNC_THROTTLE_MS = 20_000
/** Lazy sync from page loads only if data is at least this stale. */
const LAZY_SYNC_STALE_MS = 45_000

// ---------------------------------------------------------------------------
// Entry / token
// ---------------------------------------------------------------------------

export interface EntryContext {
  entry: NdEntryRow
  ndPool: NdPoolRow
  pool: { id: string; name: string; status: string; org_id: string }
}

export async function getEntryByToken(admin: Admin, token: string): Promise<EntryContext | null> {
  if (!TOKEN_RE.test(token)) return null

  const { data: entry } = await admin
    .from('nd_entries')
    .select('*')
    .eq('access_token', token)
    .eq('active', true)
    .maybeSingle()
  if (!entry) return null

  const { data: ndPool } = await admin.from('nd_pools').select('*').eq('id', entry.nd_pool_id).single()
  if (!ndPool) return null

  const { data: pool } = await admin
    .from('pools')
    .select('id, name, status, org_id')
    .eq('id', ndPool.pool_id)
    .single()
  if (!pool) return null

  // Presence stamp: drives the "Opened" / "Never opened" status on the commissioner
  // dashboard. Awaited on purpose: the query builder is lazy and never fires
  // unless awaited or .then()'d. Throttled so a busy player isn't a write per call.
  const staleBefore = new Date(Date.now() - 10 * 60 * 1000).toISOString()
  await admin
    .from('nd_entries')
    .update({ last_seen_at: new Date().toISOString() })
    .eq('id', entry.id)
    .or(`last_seen_at.is.null,last_seen_at.lt.${staleBefore}`)

  return { entry, ndPool, pool }
}

export function entryDisplayName(e: Pick<NdEntryRow, 'display_name' | 'email'>): string {
  if (e.display_name?.trim()) return e.display_name.trim()
  return e.email.split('@')[0]
}

/** True when the token belongs to an entry the commissioner has disabled (so the page can say so instead of 404). */
export async function isDisabledEntry(admin: Admin, token: string): Promise<boolean> {
  if (!TOKEN_RE.test(token)) return false
  const { data } = await admin.from('nd_entries').select('id').eq('access_token', token).eq('active', false).maybeSingle()
  return !!data
}

