export type CommissionerCheck =
  | { ok: true; userId: string; email: string | null; displayName: string | null; ndPool: NdPoolRow; pool: { id: string; org_id: string; name: string } }
  | { ok: false; status: number; error: string }

export async function requireCommissioner(admin: Admin, ndPoolId: string): Promise<CommissionerCheck> {
  const session = await createSessionClient()
  const { data: { user } } = await session.auth.getUser()
  if (!user) return { ok: false, status: 401, error: 'Unauthorized' }

  const { data: ndPool } = await admin.from('nd_pools').select('*').eq('id', ndPoolId).single()
  if (!ndPool) return { ok: false, status: 404, error: 'Pool not found' }
  const { data: pool } = await admin.from('pools').select('id, org_id, name').eq('id', ndPool.pool_id).single()
  if (!pool) return { ok: false, status: 404, error: 'Pool not found' }

  const [{ data: profile }, { data: orgMembership }, { data: poolMembership }] = await Promise.all([
    session.from('profiles').select('is_super_admin, display_name').eq('id', user.id).single(),
    session.from('org_memberships').select('role').eq('org_id', pool.org_id).eq('user_id', user.id).maybeSingle(),
    session.from('pool_memberships').select('role').eq('pool_id', pool.id).eq('user_id', user.id).maybeSingle(),
  ])
  const isSuperAdmin = checkSuperAdmin(profile)
  const isOrgAdmin = checkOrgAdmin(orgMembership, isSuperAdmin)
  if (!checkPoolCommissioner(poolMembership, isOrgAdmin)) {
    return { ok: false, status: 403, error: 'Commissioner access required' }
  }
  return { ok: true, userId: user.id, email: user.email?.toLowerCase() ?? null, displayName: profile?.display_name ?? null, ndPool, pool }
}

/** Super admin OR commissioner of any ND pool in the season. For shared-schedule writes. */
export async function requireSeasonCommissioner(admin: Admin, seasonYear: number): Promise<{ ok: true; userId: string } | { ok: false; status: number; error: string }> {
  const session = await createSessionClient()
  const { data: { user } } = await session.auth.getUser()
  if (!user) return { ok: false, status: 401, error: 'Unauthorized' }
  const { data: allowed } = await session.rpc('is_nd_season_commissioner', { p_season: seasonYear })
  if (!allowed) return { ok: false, status: 403, error: 'Commissioner access required' }
  return { ok: true, userId: user.id }
}

