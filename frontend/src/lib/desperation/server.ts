/** Recompute nd_week_scores for every entry in every pool of this season. */
export async function recomputeWeekScores(admin: Admin, seasonYear: number, week: number) {
  const games = await getWeekGames(admin, seasonYear, week)
  if (games.length === 0) return
  const gameIds = games.map((g) => g.id)
  const finalized = games.every(isTerminal)

  const { data: pools } = await admin.from('nd_pools').select('id').eq('season_year', seasonYear)
  if (!pools?.length) return
  const { data: entries } = await admin
    .from('nd_entries')
    .select('id')
    .in('nd_pool_id', pools.map((p) => p.id))
  if (!entries?.length) return

  const { data: picks } = await admin
    .from('nd_picks')
    .select('entry_id, game_id, selection')
    .in('game_id', gameIds)

  const byEntry = new Map<string, NdPick[]>()
  for (const p of picks ?? []) {
    const list = byEntry.get(p.entry_id) ?? []
    list.push({ game_id: p.game_id, selection: p.selection as NdPick['selection'] })
    byEntry.set(p.entry_id, list)
  }

  const rows: Tables['nd_week_scores']['Insert'][] = entries.map((e) => {
    const s = scoreWeek(byEntry.get(e.id) ?? [], games)
    return {
      entry_id: e.id,
      season_year: seasonYear,
      week_number: week,
      picks_made: s.picksMade,
      qualifying_picks: s.qualifying,
      correct_picks: s.correct,
      is_perfect: s.complete && !s.busted && s.qualifying > 0,
      points: s.finalPoints ?? 0,
      finalized,
      computed_at: new Date().toISOString(),
    }
  })

  const { error } = await admin.from('nd_week_scores').upsert(rows, { onConflict: 'entry_id,season_year,week_number' })
  if (error) throw new Error(`nd_week_scores upsert: ${error.message}`)
}

// ---------------------------------------------------------------------------
// Board — the ONLY place other entries' picks are read
// ---------------------------------------------------------------------------

export async function buildBoard(
  admin: Admin,
  ctx: EntryContext,
  week: NdWeek,
  games: NdGame[],
  now: Date = new Date()
): Promise<Board> {
  const { data: entries } = await admin
    .from('nd_entries')
    .select('id, email, display_name')
    .eq('nd_pool_id', ctx.ndPool.id)
    .eq('active', true)
    .order('created_at')
  const entryIds = (entries ?? []).map((e) => e.id)

  const gameIds = games.map((g) => g.id)
  const { data: picks } = gameIds.length && entryIds.length
    ? await admin.from('nd_picks').select('entry_id, game_id, selection').in('entry_id', entryIds).in('game_id', gameIds)
    : { data: [] as Array<{ entry_id: string; game_id: string; selection: string }> }

  // Season total = finalized weeks only (see sumSeasonPoints)
  const { data: seasonScores } = entryIds.length
    ? await admin
        .from('nd_week_scores')
        .select('entry_id, points, finalized')
        .in('entry_id', entryIds)
        .eq('season_year', ctx.ndPool.season_year)
        .eq('finalized', true)
    : { data: [] as Array<{ entry_id: string; points: number; finalized: boolean }> }
  const seasonTotals = sumSeasonPoints(seasonScores ?? [])

  // One gate for everything about other entries: locked week → all visible
  const weekVisible = isWeekLocked(week, now)

  const picksByEntry = new Map<string, NdPick[]>()
  for (const p of picks ?? []) {
    const list = picksByEntry.get(p.entry_id) ?? []
    list.push({ game_id: p.game_id, selection: p.selection as NdPick['selection'] })
    picksByEntry.set(p.entry_id, list)
  }

  const boardEntries: BoardEntry[] = (entries ?? []).map((e) => {
    const isMe = e.id === ctx.entry.id
    const all = picksByEntry.get(e.id) ?? []
    const show = isMe || weekVisible
    return {
      id: e.id,
      name: entryDisplayName(e),
      isMe,
      pickCount: show ? all.length : null,
      picks: show ? Object.fromEntries(all.map((p) => [p.game_id, p.selection])) : {},
      score: show ? scoreWeek(all, games) : null,
      seasonPoints: seasonTotals.get(e.id) ?? 0,
    }
  })

  return { week, games, countsVisible: weekVisible, entries: boardEntries }
}
