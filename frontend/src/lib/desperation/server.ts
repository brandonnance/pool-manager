export async function getWeeks(admin: Admin, seasonYear: number): Promise<NdWeek[]> {
  const { data } = await admin
    .from('nd_weeks')
    .select('id, season_year, week_number, lock_at, first_kickoff_at, last_kickoff_at, status, finalized_at')
    .eq('season_year', seasonYear)
    .order('week_number')
  return (data ?? []) as NdWeek[]
}

export async function getWeekGames(admin: Admin, seasonYear: number, week: number): Promise<NdGame[]> {
  const { data } = await admin
    .from('nd_games')
    .select('id, season_year, week_number, espn_game_id, home_team, home_abbr, home_logo, away_team, away_abbr, away_logo, kickoff_at, venue, neutral_site, home_score, away_score, status, period, clock, winner, qualifies, last_synced_at, spread, over_under, odds_details, odds_provider')
    .eq('season_year', seasonYear)
    .eq('week_number', week)
    .order('kickoff_at')
  return (data ?? []) as NdGame[]
}

